"""Build the validation comparison table from reports/metrics.json (never hand-typed).

Usage:  python -m src.compare_models
Writes: reports/model_comparison.md
"""

import json
from pathlib import Path

ML_DIR = Path(__file__).resolve().parents[1]

ROWS = [  # (section, key, display name)
    ("baselines", "majority", "Majority (constant score)"),
    ("baselines", "random", "Random"),
    ("baselines", "meta_lgbm", "(b) Meta only, LightGBM"),
    ("baselines", "tfidf_lr", "(c) TF-IDF word+char, LR"),
    ("baselines", "tfidf_meta_lgbm", "(d) TF-IDF + meta, LightGBM"),
    ("embeddings", "emb_lr", "(e) MiniLM embeddings, LR"),
    ("embeddings", "emb_meta_lgbm", "(f) MiniLM embeddings + meta, LightGBM"),
    ("transformer", "distilbert", "(g) DistilBERT fine-tuned (250k train subsample)"),
]


def table(metrics: dict) -> str:
    lines = ["| Model | PR-AUC | PR-AUC (dedup) | ROC-AUC | F1 (val-tuned thr.) | P@top10% "
             "| per-month PR-AUC min–max |",
             "|---|---|---|---|---|---|---|"]
    for section, key, name in ROWS:
        r = metrics.get(section, {}).get(key)
        if r is None:
            continue
        v, d = r["val"], r["val_deduped"]
        pm = r["val_per_month_pr_auc"].values()
        lines.append(f"| {name} | {v['pr_auc']:.4f} | {d['pr_auc']:.4f} | {v['roc_auc']:.4f} "
                     f"| {v['f1']:.4f} | {v['precision_at_top10']:.4f} "
                     f"| {min(pm):.4f}–{max(pm):.4f} |")
    return "\n".join(lines)


def main() -> None:
    metrics = json.loads((ML_DIR / "reports" / "metrics.json").read_text())
    md = ("# Model comparison: validation (2025-09..2026-04)\n\n"
          "Generated by `python -m src.compare_models` from `reports/metrics.json`. "
          "Chance PR-AUC = positive rate (~0.10).\n\n" + table(metrics) + "\n")
    sanity = {s: metrics[s].get("sanity_shuffled_labels") for s in ("baselines", "embeddings")
              if s in metrics}
    md += "\nShuffled-label sanity (val PR-AUC, expect ~0.10): " + json.dumps(sanity) + "\n"
    out = ML_DIR / "reports" / "model_comparison.md"
    out.write_text(md, encoding="utf-8")
    print(md)


if __name__ == "__main__":
    main()
